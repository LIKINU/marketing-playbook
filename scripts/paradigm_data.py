def check_trait_guide():
    """条件章节的标题**必须都有填写指引** —— 否则等于给了空表不给填法。"""
    return [(tr, h) for tr, hs in TRAIT_HEADS.items() for h in hs if h not in GUIDE]


def norm(s):
    """归一化标题：去空白、砍掉括号说明。查 GUIDE 一律走这里。"""
    s = "".join(str(s).split())
    for cut in ("（", "("):
        if cut in s:
            s = s.split(cut)[0]
    return s.rstrip("：:")


_NORM_GUIDE = {}
for _k, _v in GUIDE.items():
    _NORM_GUIDE[norm(_k)] = _v
_NORM_OVERRIDE = {}
for _k, _v in OVERRIDE.items():
    _NORM_OVERRIDE[(norm(_k[0]), norm(_k[1]))] = _v


def guide_for(tier, head):
    """取某档位某节的指引；先看档位覆写，再看通用。查不到回 None。"""
    k = norm(head)
    ov = _NORM_OVERRIDE.get((norm(tier), k))
    if ov:
        merged = dict(_NORM_GUIDE.get(k, {}))
        merged.update(ov)
        return merged
    return _NORM_GUIDE.get(k)


def guides_for_tier(tier):
    """回传 [(标题, 指引 dict or None), ...]，顺序即骨架顺序。"""
    return [(h, guide_for(tier, h)) for h in SKELETON_HEADS.get(tier, [])]


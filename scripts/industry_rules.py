def detect(text, explicit=None):
    """判受监管行业。回 key 或 None（长尾行业回 None，由调用方走 GENERIC）。

    ⚠️ **`explicit`（门禁里的「客户行业」）优先，关键词计数只是回退。**
    为什么：实测把一份**医美**客户规则表（其余字段留着模板里的「茶饮」字样）喂进来，
    关键词计数让「餐饮食品」（15 个关键词）**打赢了「医美医疗」** —— 因为比的是命中个数，
    不是信号强弱。客户自己写的行业是**权威**，关键词只能在没有这一项时兜底。
    """
    # ① 显式声明优先
    if explicit:
        s = str(explicit)
        for key, d in INDUSTRIES.items():
            if key in s or any(k in s for k in d["kw"]):
                return key
    if not text:
        return None
    blob = text if isinstance(text, str) else json.dumps(text, ensure_ascii=False)
    # ② 关键词计数回退：**平票就回 None**（宁可走 GENERIC 兜底，也不猜错行业）
    hits = sorted(((sum(1 for k in d["kw"] if k in blob), key)
                   for key, d in INDUSTRIES.items()), reverse=True)
    if hits and hits[0][0] > 0 and (len(hits) < 2 or hits[0][0] > hits[1][0]):
        return hits[0][1]
    return None


# 门禁里「客户行业」可能的字段名（`composer` 与 `gate_check` 共用同一套）
EXPLICIT_KEYS = ["客户行业", "所属行业", "行业类型", "行业"]


def explicit_from(rules):
    """从《任务规则表》里找显式声明的行业（顶层／gate／治理块都找）。缺失回 None。"""
    if not isinstance(rules, dict):
        return None
    pools = [rules]
    for k in ("gate", "门禁", "门禁内容", "governance", "治理", "治理块"):
        v = rules.get(k)
        if isinstance(v, dict):
            pools.append(v)
    for pool in pools:
        for k in EXPLICIT_KEYS:
            v = pool.get(k)
            if v is not None and str(v).strip():
                return str(v).strip()
    return None


def get(key):
    return INDUSTRIES.get(key) or None


def section(key, title_head="### 3.5 行业资质与宣称边界"):
    """把某个行业的资质／禁语／依据渲染成可注入骨架的 markdown（含逐项表格）。"""
    d = get(key)
    ind = key or "（长尾／一般行业）"
    d = d or GENERIC
    lic = "\n".join(f"| {n} | {a} | {r} | {{FILL}} | {{FILL}} |" for n, a, r in d["licenses"])
    ban = "\n".join(f"| {b} | {{FILL}} |" for b in d["banned"])
    clm = "\n".join(f"- {c}" for c in d["claims"])
    bas = "／".join(d["basis"])
    return (
        f"{title_head}（**本方案识别为受监管行业：{ind}**）\n"
        f"> 3.2 那张表是**全行业通用**的禁用词；这一节是**本行业专门规定**。\n"
        f"> 依据（须由客户法务或平台规则复核）：{bas}\n\n"
        f"**① 资质清单**（发布前必须齐；文号与有效期要能当场拿出来）\n"
        f"| 资质名称 | 发证机关 | 要点 | **我方持有？** | **证书编号／有效期** |\n"
        f"|---|---|---|---|---|\n{lic}\n\n"
        f"**② 本行业禁语与禁用做法**（通用禁用词之外的）\n"
        f"| 禁止表述或做法 | **替换说法** |\n|---|---|\n{ban}\n\n"
        f"**③ 宣称边界**\n{clm}\n"
        f"- 灰区怎么办（拿不准时谁拍板、留什么依据）：{{FILL}}\n\n"
        f"> ⛔ **本条不是法律意见**：以上是「该去核什么」的清单。\n"
        f"> 具体条文适用与最新要求，发布前必须由**客户法务或平台规则**复核一次；\n"
        f"> 平台侧（如小红书／抖音的行业类目规则）常比法规更严，两套都要看。\n\n"
    )


def main():
    ap = argparse.ArgumentParser(
        description="受监管行业的资质与宣称边界（数据表；供 composer 注入条件章节 3.5）")
    ap.add_argument("--list", action="store_true", help="列出所有受监管行业与关键词数")
    ap.add_argument("--detect", metavar="TEXT", help="判行业，回 key（无命中则回空）")
    ap.add_argument("--explicit", metavar="行业", help="显式声明的行业（优先于关键词计数）")
    ap.add_argument("--section", metavar="TEXT", help="按文本判行业并印出该节 markdown")
    ap.add_argument("--industry", metavar="KEY", help="直接按 key 印出该节")
    ap.add_argument("--json", action="store_true", help="以 JSON 输出（配合 --detect／--list）")
    a = ap.parse_args()

    if a.list:
        if a.json:
            print(json.dumps({k: {"kw": len(v["kw"]), "licenses": len(v["licenses"]),
                                  "banned": len(v["banned"])} for k, v in INDUSTRIES.items()},
                             ensure_ascii=False, indent=2))
        else:
            print(f"受监管行业共 {len(INDUSTRIES)} 类（长尾行业走 GENERIC 兜底）：")
            for k, v in INDUSTRIES.items():
                print(f"  · {k}：关键词 {len(v['kw'])} 个｜资质 {len(v['licenses'])} 项｜"
                      f"禁语 {len(v['banned'])} 条｜依据 {len(v['basis'])} 部")
        sys.exit(0)

    if a.industry:
        if a.industry not in INDUSTRIES:
            print(f"未知行业 key：{a.industry}（用 --list 看全部）")
            sys.exit(2)
        print(section(a.industry))
        sys.exit(0)

    if a.detect:
        k = detect(a.detect, explicit=a.explicit)
        if a.json:
            print(json.dumps({"industry": k}, ensure_ascii=False))
        else:
            print(k if k else "（未命中受监管行业 → 走 GENERIC 兜底）")
        sys.exit(0)

    if a.section:
        k = detect(a.section, explicit=a.explicit)
        print(section(k))
        sys.exit(0)

    ap.print_help()
    sys.exit(2)



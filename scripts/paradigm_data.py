"""范式库资料层（2026-09-17）。

用户原话：「每一个都需要有一个范式，例如B端的、C端的、小客户的，都需要有他们各自的
一个范式，不仅只有大纲，也需要有里面的内容可以参考。」

→ 每个档位（速览／标准／大赛／B端／G端／投标）都要有**自己的范式**：
  ① 骨架（章节树，由 composer 既有逻辑产出，本档不重复定义）
  ② 每节的**填充指引**（该写什么／写几句／必须含哪几个数）
  ③ 每节的**关键句片段**（可直接改写套用，带 `【填】` 占位）

设计原则（避免两份真相漂移）：
- **骨架的唯一真相在 `composer.py`**（build_skeleton / build_lite / SCENE_SECTIONS）。
- 本档只提供「按标题查的指引」`GUIDE`，外加少数**档位覆写** `OVERRIDE`。
- `scripts/build_paradigm.py` 把 composer 的骨架 ＋ 本档的指引拼成
  `references/12-范式库.md`；`composer.py --internal` 亦直接读本档。
  → 改骨架只改 composer，改指引只改本档，两边不会打架。

一节指引的四个字段：
  what  该写什么（一句话）
  size  写几句／几行
  must  必须含哪几个硬要素（缺一即不合格）
  lines 关键句片段（可直接改写套用的句式，数值一律用 【填】 占位，不得编造）
"""

